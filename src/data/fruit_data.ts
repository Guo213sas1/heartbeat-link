export function getBabyStatus(dueDateStr: string): {
  daysLeft: number;
  hoursLeft: number;
  currentWeek: number;
  daysIntoWeek: number;
  currentData: BabyGrowth;
  isOverdue: boolean;
  isReady: boolean;
} {
  const today = new Date();
  const dueDate = new Date(dueDateStr);

  const diffTime = dueDate.getTime() - today.getTime();
  const totalDays = Math.floor(diffTime / (1000 * 60 * 60 * 24));
  const totalHours = Math.floor(diffTime / (1000 * 60 * 60));

  const pregnancyStartDate = new Date(dueDate);
  pregnancyStartDate.setDate(pregnancyStartDate.getDate() - 280);

  const totalPregnancyDays = Math.floor((today.getTime() - pregnancyStartDate.getTime()) / (1000 * 60 * 60 * 24));
  const currentWeek = Math.min(40, Math.max(4, Math.floor(totalPregnancyDays / 7)));
  const daysIntoWeek = totalPregnancyDays % 7;

  const currentData = growthData.find(d => d.week === currentWeek) || growthData[growthData.length - 1];

  return {
    daysLeft: Math.max(0, totalDays),
    hoursLeft: Math.max(0, totalHours % 24),
    currentWeek: Math.min(40, currentWeek),
    daysIntoWeek,
    currentData,
    isOverdue: totalDays < 0,
    isReady: totalDays <= 7 && totalDays >= 0
  };
}
